export const LangContext = createContext({ lang: 'mr', setLang: () => {} })
export const useLang = () => useContext(LangContext)

/** Primary translation for the current language. */
export function useT() {
  const { lang } = useLang()
  const index = lang === 'mr' ? 0 : 1
  const t = (key) => (STRINGS[key] ? STRINGS[key][index] : key)
  // both languages, for labels that show one above the other
  t.pair = (key) => (STRINGS[key] ? STRINGS[key] : [key, key])
  t.pick = (mr, en) => (lang === 'mr' ? mr : en)
  t.other = (mr, en) => (lang === 'mr' ? en : mr)
  t.lang = lang
  return t
}
